// npm run openapi: writes openapi/purser.yaml, Purser Cloud's API as OpenAPI 3.1, from the route table
// (cloud/src/app.ts ROUTES, openApi) and the zod schemas its routes parse bodies with. The cloud serves the same document
// at /openapi.json and /v1/openapi.json. test/openapi-spec.test.ts fails when the file and the code disagree.

import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { openApi } from "../cloud/src/app.js";
import { toYaml } from "../cloud/src/apiSpec.js";

export const SPEC_FILE = "openapi/purser.yaml";

/** The document as committed: the server is a variable (each deployment has its own host), the rest as served. */
export function openApiYaml(): string {
  const doc = openApi("https://cloud.example.invalid");
  doc.servers = [{ url: "https://{host}", description: "Your Purser Cloud", variables: { host: { default: "cloud.example.invalid", description: "The host your Purser Cloud runs on" } } }];
  return "# Purser Cloud API, OpenAPI 3.1. Generated by `npm run openapi` from the route table (cloud/src/app.ts) and its zod\n"
    + "# schemas; do not edit by hand (test/openapi-spec.test.ts fails when it and the code disagree). Test money only.\n"
    + toYaml(doc);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(SPEC_FILE, openApiYaml());
  console.log(`wrote ${SPEC_FILE}`);
}
