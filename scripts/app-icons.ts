// npx tsx scripts/app-icons.ts: the installed app's icons (docs/app/README.md), rendered by the Chromium this machine has
// (Playwright), no network, from docs/assets/brand/purser-mark.svg, the white feather on navy. Written as PNG files to
// docs/assets/brand/app/ and, as base64, to src/pwa/icons.gen.ts, which both Workers serve (kit11 and Purser Cloud).
//   app-icon-192.png, app-icon-512.png   the mark as drawn (rounded corners, transparent outside them): purpose "any"
//   app-icon-maskable-512.png            full bleed (no corners): purpose "maskable"; the feather (16 of 30 units,
//                                        centred) already lies inside the safe zone, the centre circle of 80 %
//   app-icon-180.png                     full bleed: the apple-touch-icon (iOS rounds it itself)
// And the iPhone launch screens (apple-touch-startup-image, the site only: iOS makes none from the manifest), one per
// screen size below, portrait: the navy background with the mark in the middle. Android draws its own from the manifest.
// test/pwa.test.ts holds the files, the generated module and the manifest to the same bytes and sizes.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { chromium } from "playwright";

const MARK = readFileSync(new URL("../docs/assets/brand/purser-mark.svg", import.meta.url), "utf8").trim();
/** The mark with its square's corners removed: full bleed, for a launcher or iOS that cuts its own shape. */
const bleed = MARK.replace(/ rx="[\d.]+"/, "");
if (bleed === MARK) throw new Error("purser-mark.svg has no rx on its square: the full-bleed icon would be the same");

export const APP_ICONS = [
  { name: "app-icon-192.png", size: 192, svg: MARK },
  { name: "app-icon-512.png", size: 512, svg: MARK },
  { name: "app-icon-maskable-512.png", size: 512, svg: bleed },
  { name: "app-icon-180.png", size: 180, svg: bleed },
] as const;

/** iPhone screens in CSS px and their pixel ratio (the current models and the SE): one launch image each. */
export const SPLASH_SCREENS = [
  { w: 440, h: 956, dpr: 3 }, { w: 430, h: 932, dpr: 3 }, { w: 428, h: 926, dpr: 3 }, { w: 402, h: 874, dpr: 3 },
  { w: 393, h: 852, dpr: 3 }, { w: 390, h: 844, dpr: 3 }, { w: 375, h: 667, dpr: 2 },
] as const;

const browser = await chromium.launch();
async function png(svg: string, size: number): Promise<Buffer> {
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  const sized = svg.replace(/ width="\d+" height="\d+"/, "").replace("<svg ", `<svg width="${size}" height="${size}" `);
  await page.setContent(`<html><body style="margin:0;background:transparent">${sized}</body></html>`);
  const b = await page.locator("svg").screenshot({ omitBackground: true, type: "png" });
  await page.close();
  return b;
}
const out = new URL("../docs/assets/brand/app/", import.meta.url);
mkdirSync(out, { recursive: true });
const lines: string[] = [];
for (const icon of APP_ICONS) {
  const b = await png(icon.svg, icon.size);
  writeFileSync(new URL(icon.name, out), b);
  lines.push(`  ${JSON.stringify(icon.name)}: ${JSON.stringify(b.toString("base64"))},`);
  console.log(`docs/assets/brand/app/${icon.name}: ${icon.size} px, ${b.length} B`);
}
for (const s of SPLASH_SCREENS) {
  const page = await browser.newPage({ viewport: { width: s.w, height: s.h }, deviceScaleFactor: s.dpr });
  await page.setContent(`<html><body style="margin:0;height:100vh;background:#0b1220;display:grid;place-items:center">${MARK.replace(/ width="\d+" height="\d+"/, "").replace("<svg ", '<svg width="112" height="112" ')}</body></html>`);
  const b = await page.screenshot({ type: "png" });
  await page.close();
  const name = `app-splash-${s.w * s.dpr}x${s.h * s.dpr}.png`;
  writeFileSync(new URL(name, out), b);
  console.log(`docs/assets/brand/app/${name}: ${b.length} B`);
}
await browser.close();
writeFileSync(new URL("../src/pwa/icons.gen.ts", import.meta.url), `// Generated by npx tsx scripts/app-icons.ts from docs/assets/brand/purser-mark.svg. Do not edit.
/** The installed app's icons, PNG, base64, by the name both Workers serve them under (/assets/<name>). */
export const APP_ICON_PNGS: Record<string, string> = {
${lines.join("\n")}
};
`);
