// npm run cloud:icons: Purser's icons for both Workers (the site, kit11, and Purser Cloud, purser-try), drawn from the
// site header's own mark (src/ui/brand/mark.ts) and written to src/ui/brand/icons.gen.ts: the SVG, PNGs at 180
// (apple-touch-icon, full bleed: iOS rounds it) and 512 px, and a favicon.ico holding PNGs at 32 and 48 px; and the same
// SVG to src/ui/brand/favicon.svg (the README's and the social preview's mark). Rendered by the Chromium this machine has
// (Playwright), no network. A browser tab, a home-screen shortcut and an MCP client all show the one mark.

import { writeFileSync } from "node:fs";
import { chromium } from "playwright";
import { markSvg } from "../../src/ui/brand/mark.js";

const browser = await chromium.launch();
async function png(source: string, size: number): Promise<Buffer> {
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  await page.setContent(`<html><body style="margin:0;background:transparent">${source.replace("<svg ", `<svg width="${size}" height="${size}" `)}</body></html>`);
  const b = await page.locator("svg").screenshot({ omitBackground: true, type: "png" });
  await page.close();
  return b;
}
const rounded = markSvg(), square = markSvg({ bleed: true });
const [p32, p48, p180, p512] = [await png(rounded, 32), await png(rounded, 48), await png(square, 180), await png(rounded, 512)];
await browser.close();

/** An ICO that holds PNG images (every browser since 2007 reads them). */
function ico(images: { size: number; data: Buffer }[]): Buffer {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach((im, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(im.size >= 256 ? 0 : im.size, e); head.writeUInt8(im.size >= 256 ? 0 : im.size, e + 1);
    head.writeUInt8(0, e + 2); head.writeUInt8(0, e + 3); head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(im.data.length, e + 8); head.writeUInt32LE(offset, e + 12);
    offset += im.data.length;
  });
  return Buffer.concat([head, ...images.map((im) => im.data)]);
}

const out = `// Generated by npm run cloud:icons (cloud/scripts/brandIcons.ts) from src/ui/brand/mark.ts, the site header's mark. Do not edit.
export const ICON_SVG = ${JSON.stringify(rounded)};
export const ICON_PNG_180 = ${JSON.stringify(p180.toString("base64"))};
export const ICON_PNG_512 = ${JSON.stringify(p512.toString("base64"))};
export const ICON_ICO = ${JSON.stringify(ico([{ size: 32, data: p32 }, { size: 48, data: p48 }]).toString("base64"))};
`;
writeFileSync(new URL("../../src/ui/brand/icons.gen.ts", import.meta.url), out);
writeFileSync(new URL("../../src/ui/brand/favicon.svg", import.meta.url), `${rounded}\n`);
console.log(`src/ui/brand/icons.gen.ts: ${out.length} bytes (png 180 ${p180.length} B, 512 ${p512.length} B, ico ${ico([{ size: 32, data: p32 }, { size: 48, data: p48 }]).length} B)`);
