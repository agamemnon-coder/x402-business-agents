// npm run cloud:font: writes cloud/src/font.gen.ts, the SHA-256 of the console's font (Inter, src/ui/inter.woff2, OFL).
// The font itself is served by the site Worker (kit11) through the console's SITE binding; the Worker keeps
// only its hash, for the offline worker's version (cloud/src/pwa.ts). test/cloud-console.test.ts holds the two equal.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const sha = createHash("sha256").update(readFileSync(new URL("../../src/ui/inter.woff2", import.meta.url))).digest("hex");
writeFileSync(new URL("../src/font.gen.ts", import.meta.url), `// Generated by npm run cloud:font from src/ui/inter.woff2 (Inter, OFL: src/ui/inter-LICENSE.txt). Do not edit.\n// The font is served by the site Worker (kit11) through the SITE binding; this is its SHA-256.\nexport const INTER_WOFF2_SHA256 = "${sha}";\n`);
