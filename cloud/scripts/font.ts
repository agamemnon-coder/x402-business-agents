// npm run cloud:font: writes cloud/src/font.gen.ts, the console's font (Inter, src/ui/inter.woff2, OFL) as base64,
// because the Worker reads no files. test/cloud-console.test.ts holds the two equal.
import { readFileSync, writeFileSync } from "node:fs";

const b64 = readFileSync(new URL("../../src/ui/inter.woff2", import.meta.url)).toString("base64");
writeFileSync(new URL("../src/font.gen.ts", import.meta.url), `// Generated by npm run cloud:font from src/ui/inter.woff2 (Inter, OFL: src/ui/inter-LICENSE.txt). Do not edit.\nexport const INTER_WOFF2_B64 = "${b64}";\n`);
