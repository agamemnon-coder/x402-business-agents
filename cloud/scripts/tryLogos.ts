// npm run cloud:logos: the partners' official logo files, unaltered (docs/assets/logos/SOURCES.md), as base64 in
// cloud/src/try/logos.gen.ts, so purser-try serves the very bytes the site serves at the same paths (/assets/logo-*)
// for /try's start screen. test/try-run.test.ts holds each to its file and its recorded SHA-256.
import { readFileSync, writeFileSync } from "node:fs";

const FILES: [path: string, type: string, source: string][] = [
  ["/assets/logo-alta.svg", "image/svg+xml", "src/ui/logos/alta.svg"],
  ["/assets/logo-claude-slate.svg", "image/svg+xml", "docs/assets/logos/claude-logo-slate.svg"],
];
const rows = FILES.map(([path, type, source]) => `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, source: ${JSON.stringify(source)}, b64: ${JSON.stringify(readFileSync(source).toString("base64"))} },`);
writeFileSync("cloud/src/try/logos.gen.ts", `// Generated by npm run cloud:logos (cloud/scripts/tryLogos.ts) from the partners' official files, unaltered. Do not edit.
export const LOGO_FILES: Record<string, { type: string; source: string; b64: string }> = {
${rows.join("\n")}
};
`);
