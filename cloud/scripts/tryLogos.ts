// npm run cloud:logos: the partners' official logo files, unaltered (docs/assets/logos/SOURCES.md), as base64 in
// cloud/src/try/logos.gen.ts, so purser-try serves the very bytes the site serves at the same paths (/assets/logo-*)
// for /try's start screen. test/try-run.test.ts holds each to its file and its recorded SHA-256. Also the "Built on
// Airwallex" badge's file as cloud/src/awxLogo.gen.ts (below).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const FILES: [path: string, type: string, source: string][] = [
  ["/assets/logo-alta.svg", "image/svg+xml", "src/ui/logos/alta.svg"],
  ["/assets/logo-claude-slate.svg", "image/svg+xml", "docs/assets/logos/claude-logo-slate.svg"],
];
const rows = FILES.map(([path, type, source]) => `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, source: ${JSON.stringify(source)}, b64: ${JSON.stringify(readFileSync(source).toString("base64"))} },`);
writeFileSync("cloud/src/try/logos.gen.ts", `// Generated by npm run cloud:logos (cloud/scripts/tryLogos.ts) from the partners' official files, unaltered. Do not edit.
export const LOGO_FILES: Record<string, { type: string; source: string; b64: string }> = {
${rows.join("\n")}
};
`);

// Site audit, 19 Nov (docs/evidence/site-quality.md finding 4): the "Built on Airwallex" badge's file, as a data URL for
// Purser Cloud's Airwallex tab and its pages, and served at the site's address from this origin (cloud/src/console.ts).
// It is the site's own file (src/ui/builtOn.ts AIRWALLEX_LOGO_FILE): the official wordmark scaled to 306 x 42, resized
// only; the original stays in src/ui/logos/airwallex.png, byte for byte.
const AWX = "src/ui/logos/airwallex-306x42.png";
const awx = readFileSync(AWX);
writeFileSync("cloud/src/awxLogo.gen.ts", `// Generated by npm run cloud:logos (cloud/scripts/tryLogos.ts) from ${AWX}, byte for byte. Do not edit.
// The official Airwallex wordmark (src/ui/logos/airwallex.png) scaled to 306 x 42 (resized only: not redrawn, not
// recoloured), as a data URL for Purser Cloud's Airwallex tab and its Overview card ("Built on Airwallex", never an
// endorsement). test/awx-live.test.ts holds it equal to the file. sha256 ${createHash("sha256").update(awx).digest("hex")}
export const AIRWALLEX_LOGO_DATA_URL = "data:image/png;base64,${awx.toString("base64")}";
`);
