// The scenario library (master list line 301): every event in every layout, 27 scenarios, built from the blocks
// (./blocks.ts) in a fixed order, so a scenario's id and its texts never change between builds. Each carries `expect`,
// the right answer (refuse, ask a person first, or pay after the visitor's signature) with the reason; the engine's
// deterministic checks were measured against every one with no Claude (test/try-scenarios.test.ts). The library itself
// claims nothing "live": the live part, when switched on, is Claude reading the PDF in the visitor's company.
import { buildEvent, EVENTS, type Event, type Expect, type Lang, type ScenarioFile } from "./blocks.js";

export interface Scenario { id: string; event: Event; lang: Lang; title: string; files: ScenarioFile[]; expect: Expect }

export const LANGS: Lang[] = ["en", "nl", "de"];

/** The library, in its fixed order: events outer, layouts inner. */
export const LIBRARY: Scenario[] = EVENTS.flatMap((event, ei) => LANGS.map((lang, li) => {
  const b = buildEvent(event, lang, ei * LANGS.length + li);
  return { id: `${event}-${lang}`, event, lang, title: b.title, files: b.files, expect: b.expect };
}));

/** The generated file (cloud/src/try/scenarios.gen.ts): each scenario's files as PDFs (base64), and its expect. */
export function scenariosFile(pdfs: string[][]): string {
  const items = LIBRARY.map((s, i) => ({ id: s.id, event: s.event, lang: s.lang, title: s.title, expect: s.expect, files: s.files.map((f, j) => ({ filename: f.filename, base64: pdfs[i]![j]! })) }));
  return `// Generated by npm run cloud:scenarios from src/try/scenarios/ (LIBRARY). Do not edit.\n// Test invoices (fake), rendered to PDF by src/e2e/documents.ts pdfOf; test/try-scenarios.test.ts holds this file up to date.\nimport type { ScenarioPdfs } from "../../../src/try/scenarios/seed.js";\n\nexport const SCENARIOS: ScenarioPdfs[] = ${JSON.stringify(items, null, 1)};\n`;
}
