/** The 5x7 dots of a character (rows top to bottom), or null for a space or a character the font does not hold. */
export function glyph(ch: string): boolean[][] | null {
  const g = G[ch];
  return g ? g.split(" ").map((row) => [...row].map((c) => c === "#")) : null;
}

