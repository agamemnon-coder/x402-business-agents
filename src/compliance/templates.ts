// The contract templates and the transfers note (v1.5.1): the per-provider tables of
// docs/compliance/templates/ict-contract-clauses.md (DORA Art. 30), docs/compliance/templates/dpa.md (GDPR Art. 28, its
// subprocessors) and docs/compliance/transfers.md (GDPR Chapter V), rendered from the third-party register
// (docs/compliance/third-parties.json) and the record of processing (./gdpr.ts ACTIVITIES), so the three pages name the
// same providers, criticality, locations and contracts as the register. npm run compliance:controls writes the blocks;
// test/compliance-templates.test.ts fails when a page is behind. Templates, not legal advice; nothing here is a contract.

import { ACTIVITIES } from "./gdpr.js";
import { loadRegister, type Criticality, type Provider, type Register } from "./thirdParties.js";

// A Markdown table cell: pipes escaped, newlines folded (split/join, as in controls.ts, so no regex half-escapes).
const cell = (s: string) => s.split("|").join("\\|").split("\n").join(" ");

/** The providers that receive personal data: the recipients of the record of processing (docs/compliance/gdpr.md). */
export function personalDataRecipients(r: Register = loadRegister()): Provider[] {
  const used = new Set(ACTIVITIES.flatMap((a) => a.recipients));
  return r.providers.filter((p) => used.has(p.id));
}

/** The activities of the record of processing (R1 to R9) whose data a provider receives. */
const activitiesOf = (id: string) => ACTIVITIES.filter((a) => a.recipients.includes(id)).map((a) => a.id);

/** Which of Purser's parts calls a provider, from the register's code paths. */
export function calledFrom(p: Provider): string {
  const cloud = p.code.some((c) => c.startsWith("cloud/") || c.startsWith("worker/"));
  const runner = p.code.some((c) => c.startsWith("src/"));
  return cloud && runner ? "Purser Cloud and the runner" : cloud ? "Purser Cloud" : runner ? "the runner" : "neither (outside the product)";
}

/** DORA Art. 30's parts that a contract with this provider would need, by the register's criticality. */
export const ART30_PARTS: Record<Criticality, string> = {
  critical: "Art. 30(2) and 30(3)",
  important: "Art. 30(2) and 30(3)",
  optional: "Art. 30(2)",
  "not-in-product": "none: not an ICT service the product uses",
};

/** Where a provider sits for Chapter V: outside the EU, unknown, or a public chain. */
export type TransferClass = "third-country" | "not-recorded" | "public-chain" | "eu";
export function transferClass(p: Provider): TransferClass {
  if (/United States/.test(p.location)) return "third-country";
  if (/testnet/i.test(p.location)) return "public-chain";
  if (/not pinned|provider's|not documented|Sandbox|Through/.test(p.location)) return "not-recorded";
  return "eu";
}

const MECHANISM: Record<TransferClass, string> = {
  "third-country": "**Needed.** The EU-US Data Privacy Framework only if the recipient is listed under it for this data on the day; otherwise Standard Contractual Clauses (Module 3 from Purser Cloud's operator, Module 2 where the business contracts directly) with a transfer impact assessment",
  "not-recorded": "**Not known until the location is.** Record where the data is processed; if outside the EEA and with no adequacy decision, Standard Contractual Clauses with a transfer impact assessment",
  "public-chain": "**None can cover it.** A public chain is copied wherever its nodes run: keep personal data off it",
  eu: "Not needed while the data stays in the EU",
};

/** The DORA Art. 30 table of docs/compliance/templates/ict-contract-clauses.md: every provider of the register. */
export function ictProvidersBlock(r: Register = loadRegister()): string {
  const personal = new Set(personalDataRecipients(r).map((p) => p.id));
  const L = ["<!-- ict-providers:start: generated by npm run compliance:controls from docs/compliance/third-parties.json; do not edit by hand -->", ""];
  L.push(`${r.providers.length} providers in the register (as of ${r.as_of}). Criticality is Purser's own view in the register; the financial entity decides its own.`, "");
  L.push("| Provider | Criticality (register) | Art. 30 clauses the contract needs | Contract today (register) | Personal data (record of processing) | Exit plan |", "|---|---|---|---|---|---|");
  for (const p of r.providers) {
    const acts = activitiesOf(p.id);
    const data = !personal.has(p.id) ? "No"
      : transferClass(p) === "public-chain" ? `Yes (${acts.join(", ")}): written to a public chain, so keep personal data off it ([transfers](../transfers.md))`
      : `Yes (${acts.join(", ")}): a [DPA](dpa.md) and, outside the EU, a [transfer mechanism](../transfers.md)`;
    const exit = p.exit_plan ? `[exit plan](../${p.exit_plan})` : "none (not critical or important)";
    L.push(`| **${cell(p.name)}** | ${p.criticality} | ${ART30_PARTS[p.criticality]} | ${cell(p.contract)} | ${data} | ${exit} |`);
  }
  L.push("", "<!-- ict-providers:end -->");
  return L.join("\n");
}

/** Annex III of docs/compliance/templates/dpa.md: the subprocessors, from the register and the record of processing. */
export function subprocessorsBlock(r: Register = loadRegister()): string {
  const L = ["<!-- subprocessors:start: generated by npm run compliance:controls from docs/compliance/third-parties.json and src/compliance/gdpr.ts; do not edit by hand -->", ""];
  const list = personalDataRecipients(r);
  L.push(`${list.length} providers receive personal data in the record of processing. Called from: the register's code paths. A provider called only by the runner is engaged by the business itself when it runs the runner with its own accounts; it is Purser's subprocessor only where Purser's operator runs that part for the business.`, "");
  L.push("| Subprocessor | Service | Data it receives (register: Restricted and Secret) | Activities | Called from | Location (register) | Terms today (register) |", "|---|---|---|---|---|---|---|");
  for (const p of list) {
    const data = p.data_shared.filter((d) => d.level === "Restricted" || d.level === "Secret").map((d) => `${d.what} (${d.level})`).join("; ");
    L.push(`| **${cell(p.name)}** | ${cell(p.service)} | ${cell(data)} | ${activitiesOf(p.id).join(", ")} | ${calledFrom(p)} | ${cell(p.location)} | ${cell(p.contract)} |`);
  }
  L.push("", "<!-- subprocessors:end -->");
  return L.join("\n");
}

/** The per-provider table of docs/compliance/transfers.md. */
export function transfersBlock(r: Register = loadRegister()): string {
  const list = personalDataRecipients(r);
  const n = (c: TransferClass) => list.filter((p) => transferClass(p) === c).length;
  const L = ["<!-- transfers:start: generated by npm run compliance:controls from docs/compliance/third-parties.json and src/compliance/gdpr.ts; do not edit by hand -->", ""];
  L.push(`${list.length} providers receive personal data: ${n("third-country")} in the United States, ${n("not-recorded")} whose location the repository does not record in full, ${n("public-chain")} public chain${n("public-chain") === 1 ? "" : "s"}. A transfer mechanism is recorded for none of them.`, "");
  L.push("| Recipient | Location (register) | Activities | Outside the EU | Mechanism it would need | Recorded today |", "|---|---|---|---|---|---|");
  for (const p of list) {
    const c = transferClass(p);
    const outside = c === "third-country" ? "**yes**" : c === "public-chain" ? "everywhere its nodes run" : c === "not-recorded" ? "not known" : "no";
    L.push(`| **${cell(p.name)}** | ${cell(p.location)} | ${activitiesOf(p.id).join(", ")} | ${outside} | ${MECHANISM[c]} | none |`);
  }
  L.push("", "<!-- transfers:end -->");
  return L.join("\n");
}
