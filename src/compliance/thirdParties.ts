// The ICT third-party register (26 Nov; DORA Art. 28(3)): docs/compliance/third-parties.json is the source, machine-
// readable, and docs/compliance/third-parties.md is rendered from it (npm run compliance:controls). Every provider the
// code calls, with the function it supports, the data it receives (by the levels of docs/security/data-classification.md),
// its criticality, its location where the repository records one, the contract (none yet: test accounts) and how it
// would be replaced. test/compliance-third-parties.test.ts holds every outside host the code calls to a provider here,
// and every host here to the code.

import { readFileSync } from "node:fs";
import { HONEST_LINE } from "./controls.js";

export const REGISTER_FILE = "docs/compliance/third-parties.json";
export const REGISTER_FORMAT = "purser.ict-third-parties/v1";
export const CRITICALITY = ["critical", "important", "optional", "not-in-product"] as const;
export type Criticality = typeof CRITICALITY[number];
export const LEVELS = ["Secret", "Restricted", "Internal", "Public"] as const;

export interface Provider {
  id: string;
  name: string;
  service: string;
  functions: string[];
  criticality: Criticality;
  /** Hosts the code calls (literal in the code); a provider reached through another one has none. */
  hosts: string[];
  /** Hosts set by configuration, not written in the code (an RPC URL, a company's own address). */
  configured_hosts?: string;
  /** For a provider reached through another provider's hosts: that provider's id. */
  reached_through?: string;
  data_shared: { level: typeof LEVELS[number]; what: string }[];
  location: string;
  contract: string;
  substitutes: string;
  /** Required for a critical or important provider: the section of exit-plans.md. */
  exit_plan?: string;
  code: string[];
}

export interface Register { format: string; as_of: string; version: string; owner: string; review_by: string; note: string; providers: Provider[] }

export const loadRegister = (file = REGISTER_FILE): Register => JSON.parse(readFileSync(file, "utf8")) as Register;

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s: string) => `\`${s}\``;
const CRIT_WORDS: Record<Criticality, string> = { critical: "**critical**", important: "important", optional: "optional (opt-in)", "not-in-product": "not in the product" };

/** docs/compliance/third-parties.md, rendered from the register (npm run compliance:controls). */
export function registerMarkdown(r: Register = loadRegister()): string {
  const n = (c: Criticality) => r.providers.filter((p) => p.criticality === c).length;
  const L: string[] = [];
  L.push('<div align="center">', "");
  L.push('<a href="../../README.md"><picture><source media="(prefers-color-scheme: dark)" srcset="../assets/brand/purser-mark-dark.svg"><img src="../assets/brand/purser-mark.svg" alt="Purser" width="64" height="64"></picture></a>', "");
  L.push("# ICT third-party register", "");
  L.push("**Every outside service Purser's code calls: what it does for Purser, what it receives, how critical it is, and how it would be replaced.**", "");
  L.push(`[![Providers: ${r.providers.length}](https://img.shields.io/badge/providers-${r.providers.length}-2563eb?style=flat-square&labelColor=1f2937)](#the-register)&nbsp;`
    + `[![Critical: ${n("critical")}](https://img.shields.io/badge/critical-${n("critical")}-ca8a04?style=flat-square&labelColor=1f2937)](exit-plans.md)&nbsp;`
    + "[![Contracts: none yet](https://img.shields.io/badge/contracts-none_yet-475569?style=flat-square&labelColor=1f2937)](exit-plans.md#contracts-what-a-production-contract-must-include)&nbsp;"
    + "[![Test money only](https://img.shields.io/badge/money-test_only-16a34a?style=flat-square&labelColor=1f2937)](../../README.md)", "");
  L.push("</div>", "");
  L.push("<!-- Generated by npm run compliance:controls from docs/compliance/third-parties.json. Do not edit by hand. -->", "");
  L.push(`| Owner | Version | As of | Review by | Source |`, "|---|---|---|---|---|");
  L.push(`| ${r.owner} | ${r.version} | ${r.as_of} | ${r.review_by} | [third-parties.json](third-parties.json) (machine-readable) |`, "");
  L.push(`> [!IMPORTANT]`, `> ${r.note}`, "");
  L.push(`> [!NOTE]`, `> ${HONEST_LINE}`, "");
  L.push("## Who depends on whom", "");
  L.push("```mermaid", "flowchart LR");
  L.push('  P["Purser<br/>runner, relay, Cloud"]');
  for (const p of r.providers.filter((x) => x.criticality === "critical" || x.criticality === "important")) {
    const id = p.id.replace(/[^a-z0-9]/g, "");
    L.push(`  ${id}["${p.name.replace(/"/g, "'")}<br/>${p.criticality}"]`);
    L.push(p.reached_through ? `  ${p.reached_through.replace(/[^a-z0-9]/g, "")} -.->|"through"| ${id}` : `  P --> ${id}`);
  }
  L.push(`  OPT["${n("optional")} optional integrations<br/>opt-in, per company"]`, "  P -.-> OPT", "```", "");
  L.push("## The register", "");
  L.push(`${r.providers.length} providers: ${n("critical")} critical, ${n("important")} important, ${n("optional")} optional (switched on per company), ${n("not-in-product")} not in the product. Critical or important means the function it supports stops or degrades without it (DORA Art. 3(22)); each has an [exit plan](exit-plans.md).`, "");
  L.push("| Provider | Function for Purser | Data it receives (level) | Criticality | Hosts the code calls | Location | Contract | Exit and substitution |", "|---|---|---|---|---|---|---|---|");
  for (const p of r.providers) {
    const hosts = p.hosts.length ? p.hosts.map(code).join(", ") : p.reached_through ? `through ${r.providers.find((x) => x.id === p.reached_through)?.name ?? p.reached_through}` : "none";
    const conf = p.configured_hosts ? ` (${p.configured_hosts})` : "";
    const exit = p.exit_plan ? `${p.substitutes}. [Exit plan](${p.exit_plan})` : p.substitutes;
    L.push(`| **${cell(p.name)}** | ${cell(p.functions.join("; "))} | ${cell(p.data_shared.map((d) => `${d.what} (${d.level})`).join("; "))} | ${CRIT_WORDS[p.criticality]} | ${cell(hosts + conf)} | ${cell(p.location)} | ${cell(p.contract)} | ${cell(exit)} |`);
  }
  L.push("");
  L.push("## How it is kept true", "");
  L.push("- `test/compliance-third-parties.test.ts` reads every `https://` host written in `src/`, `cloud/src/` and `worker/src/`. Each is either a provider's host here, or listed in the test as not called (a documentation link, an explorer link, Purser's own deployments, a placeholder in a test case), with the reason. A new outside host fails the test until it is registered; a host here that the code no longer names fails it too.");
  L.push("- Each provider's data levels are the levels of [data-classification.md](../security/data-classification.md); a critical or important provider has an exit plan in [exit-plans.md](exit-plans.md).");
  L.push("- The register is reviewed with the AI policy ([ai-policy.md](ai-policy.md)), at the latest on its review date, and whenever a provider is added.", "");
  L.push("## What it is not", "");
  L.push("- Not DORA's register of information in the form of its implementing technical standards: Purser is not a financial entity and has no contractual arrangements to report. A financial entity that deploys Purser enters these providers in its own register.");
  L.push("- No due diligence on a provider beyond what its public documents say; no provider has been audited by Purser.", "");
  L.push("## See also", "");
  L.push("- [exit-plans.md](exit-plans.md): exit plans per critical provider, and what a production contract must include.");
  L.push("- [../privacy/data-inventory.md](../privacy/data-inventory.md#subprocessors-the-code-calls): the same providers as subprocessors of company data.");
  L.push("- [controls.md](controls.md): the control map (PC-30).", "");
  return L.join("\n");
}
