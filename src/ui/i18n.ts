/** One field of the register's English data in the page's language (unknown text stays as it is). */
export function dataText(lang: Lang, field: keyof typeof DATA_NL, text: string): string {
  if (lang !== "nl" || !text) return text;
  for (const [re, to] of DATA_NL[field] ?? []) {
    const r = new RegExp(re);
    if (r.test(text)) return text.replace(r, to);
  }
  return text;
}

