/** What a page's script starts with: its language, its catalogue and the data patterns, as JSON (no HTML in it). */
export function clientI18n(lang: Lang, keep: (key: Key) => boolean = () => true): string {
  const m = Object.fromEntries(Object.entries(MESSAGES[lang]).filter(([k]) => keep(k as Key)));
  const json = JSON.stringify({ lang, m, data: lang === "nl" ? DATA_NL : {} }).replace(/</g, "\\u003c");
  return `const L=${json};\n${I18N_JS}`;
}

