// /try's "Proof in numbers" band (15 Nov, owner: "numbers and proof on the start and the finish"): only figures measured
// in a recorded run, each read here from its record and linked to it. The Worker does not read the records itself, so
// npm run cloud:proof writes them into cloud/src/try/proof.gen.ts (test/try-proof.test.ts holds that file to this one).
// The suite's count is not here: the page reads docs/assets/test-summary.json itself, as the start already did.
// No figure is typed by hand, and none is a fraction.

import { AGENT_RUN_FILE, loadRecord, payments, split, stopStory } from "./run.js";
import { liveRunCount } from "./runs.js";
import { REPO_BLOB } from "./metalStory.js";

/** One figure: its key (the copy's label), the number, and the record it is read from. */
export interface ProofFigure { key: "runs" | "claude" | "alta" | "overLimit"; n: number; href: string }

export function tryProofFigures(): ProofFigure[] {
  const { file, standIn, record } = loadRecord();
  // The main run's figures only from the main run's own record, never from a stand-in.
  const main = !standIn && file === AGENT_RUN_FILE;
  const out: ProofFigure[] = [{ key: "runs", n: liveRunCount(), href: `${REPO_BLOB}docs/runs/README.md` }];
  if (main) {
    const s = split(record), p = payments(record), st = stopStory(record);
    out.push({ key: "claude", n: s.byClaude, href: `${REPO_BLOB}${file}` });
    if (p.sums) out.push({ key: "alta", n: p.onChain, href: `${REPO_BLOB}${file}` });
    if (st.overLimitEur !== null && Number(st.overLimitEur) === 0) out.push({ key: "overLimit", n: 0, href: `${REPO_BLOB}${file}` });
  }
  return out;
}

/** cloud/src/try/proof.gen.ts as npm run cloud:proof writes it. */
export function tryProofFile(figures: ProofFigure[] = tryProofFigures()): string {
  return `// Generated by npm run cloud:proof (cloud/scripts/tryProof.ts) from the run records (src/redesign/tryProof.ts). Do not edit.
export const PROOF_FIGURES: { key: "runs" | "claude" | "alta" | "overLimit"; n: number; href: string }[] = ${JSON.stringify(figures)};
`;
}
